	/** nامین تکرارِ یک متنِ نمونه؛ بعد از تمام شدنِ فهرست، معرفیِ کامل. */
	private static function next( $key, $list ) {
		$i                  = isset( self::$seen[ $key ] ) ? self::$seen[ $key ] : 0;
		self::$seen[ $key ] = $i + 1;
		return golzari_label( isset( $list[ $i ] ) ? $list[ $i ] : 'about' );
	}

