	/** یک تکه متن بینِ دو برچسب. */
	public static function text( $s ) {
		$core = trim( str_replace( "\xE2\x80\x8B", '', $s ) );
		if ( '' === $core ) {
			return $s;
		}
		$new = null;
		if ( 0 === strpos( $core, 'لورم ایپسوم' ) ) {
			$new = self::LOREM === $core
				? self::next( 'lorem', array( 'teacher', 'f1_d', 'f2_d', 'f3_d', 'f4_d', 'f5_d', 'f6_d' ) )
				: golzari_label( 'about' );
		} elseif ( 0 === strpos( $core, self::DESIGNS ) ) {
			$new = self::next( 'designs', array( 's1_d', 's2_d', 's3_d' ) );
		} elseif ( self::$front ) {
			$map = self::phrases();
			if ( isset( $map[ $core ] ) ) {
				$new = golzari_label( $map[ $core ] );
				// «نمونه …» در دکمه‌های نمونه‌کارها.
				if ( 0 === strpos( $core, 'نمونه ' ) ) {
					$new = 'نمونه ' . $new;
				}
			}
		}
		if ( null === $new ) {
			return $s;
		}
		// فاصله‌های دو طرف همان می‌ماند.
		preg_match( '/^(\s*).*?(\s*)$/su', $s, $m );
		return $m[1] . esc_html( $new ) . $m[2];
	}
