	/** سالِ شمسیِ امروز (برای پانویس). */
	public static function jalali_year() {
		$y = (int) gmdate( 'Y' );
		$md = (int) gmdate( 'nd' );
		return Golzari_Brand::fa_digits( $md >= 321 ? $y - 621 : $y - 622 );
	}

